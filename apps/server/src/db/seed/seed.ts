import type { Database } from "bun:sqlite";
import { SOURCE_DOCUMENT_KINDS, Stage } from "@app/schema";
import { HOUSEHOLDS, namePools, planHousehold, type HouseholdPlan, type HouseholdSpec, type ReturnPlan } from "./households";
import { demoPdf } from "./pdf";
import { createRng } from "./random";
import { loadFees, suggestedLines } from "../../money/pricing";
import { CONSENT_TEXT, currentTemplate, FILING_STATUS_LABEL, renderLetter } from "../../letters/template";
import type { Storage } from "../../storage";

// Demo world only. Builds 25 invented households spread across every pipeline stage, following the
// same gates the API will enforce, so the demo never shows a state the real product couldn't reach.

export type SeedOptions = {
  storage: Storage; // demo storage: <repo>/data/demo/uploads
  seed?: number;
  anchor?: Date; // "now" for the demo; timestamps are relative to it, ids are not
};

export type SeedSummary = {
  taxYear: number;
  households: number;
  returns: number;
  documents: number;
  logins: { role: "preparer" | "client"; email: string; label: string }[];
};

const DAY = 86_400_000;
const STAGES = Stage.options;
const reached = (stage: Stage, target: Stage) => STAGES.indexOf(stage) >= STAGES.indexOf(target);

const INTAKE_ANSWERS = JSON.stringify({ moved: false, life_changes: [], health_coverage: "employer", refund_preference: "direct_deposit_via_preparer" });

export function seedDemo(db: Database, opts: SeedOptions): SeedSummary {
  const rng = createRng(opts.seed ?? 2026);
  const anchorMs = (opts.anchor ?? new Date()).getTime();
  const taxYear = new Date(anchorMs).getUTCFullYear() - 1;
  const at = (daysAgo: number) => new Date(anchorMs - Math.round(daysAgo * DAY)).toISOString();
  const pools = namePools();

  const insert = (table: string, row: Record<string, string | number | null | undefined>) => {
    const cols = Object.keys(row).filter((c) => row[c] !== undefined);
    db.run(`INSERT INTO ${table} (${cols.join(", ")}) VALUES (${cols.map(() => "?").join(", ")})`, cols.map((c) => row[c] ?? null));
  };
  const summary: SeedSummary = { taxYear, households: 0, returns: 0, documents: 0, logins: [] };
  const emails = new Set<string>();
  const emailFor = (first: string, last: string) => {
    const base = `${first}.${last}`.toLowerCase().replace(/[^a-z.]/g, "");
    let email = `${base}@example.test`;
    for (let n = 2; emails.has(email); n++) email = `${base}${n}@example.test`;
    emails.add(email);
    return email;
  };

  const preparerId = rng.id();
  insert("users", { id: preparerId, role: "preparer", email: "preparer@belltaxprep.test", created_at: at(400), activated_at: at(400) });
  summary.logins.push({ role: "preparer", email: "preparer@belltaxprep.test", label: "Demo preparer" });

  type Ctx = { hhId: string; plan: HouseholdPlan; spec: HouseholdSpec; people: Map<string, { id: string; first: string; last: string; last4: string }>; users: Map<string, string>; sources: Map<string, string> };

  const event = (
    type: string,
    actor: { kind: "client" | "preparer" | "system" | "stripe"; userId?: string },
    where: { household?: string; engagement?: string; subjectType: string; subjectId: string; when: string; reason?: string },
  ) =>
    insert("events", {
      id: rng.id(),
      occurred_at: where.when,
      actor_kind: actor.kind,
      actor_user_id: actor.userId ?? null,
      household_id: where.household ?? null,
      engagement_id: where.engagement ?? null,
      type,
      subject_type: where.subjectType,
      subject_id: where.subjectId,
      reason: where.reason ?? null,
      data: "{}",
    });

  const writeDoc = (
    ctx: Ctx,
    doc: { kind: string; personKey: string; engagementId?: string; year?: number; requestId?: string; sourceKey?: string; sourceLabel?: string },
    state: { status: "uploaded" | "accepted" | "rejected"; when: string; rejectReason?: string },
  ) => {
    const who = ctx.people.get(doc.personKey)!;
    const docId = rng.id();
    const bytes = demoPdf([
      `Document: ${doc.kind.toUpperCase().replace(/_/g, "-")}`,
      doc.year ? `Tax year: ${doc.year}` : "Identity document",
      `Name: ${who.first} ${who.last}`,
      `SSN: 9XX-XX-${who.last4} (demo, not a real number)`,
      doc.sourceLabel ? `Issued by: ${doc.sourceLabel}` : "Issued by: n/a",
      "Generated by the Bell Tax Prep demo seed.",
    ]);
    const storageKey = opts.storage.keyFor(docId, "pdf");
    opts.storage.put(storageKey, bytes);
    insert("documents", {
      id: docId,
      person_id: who.id,
      engagement_id: doc.engagementId ?? null,
      tax_year: doc.year ?? null,
      request_id: doc.requestId ?? null,
      source_id: doc.sourceKey ? ctx.sources.get(doc.sourceKey)! : null,
      kind: doc.kind,
      status: state.status,
      reject_reason: state.rejectReason ?? null,
      filename: `${doc.kind}-${who.last.toLowerCase()}.pdf`,
      mime_type: "application/pdf",
      size_bytes: bytes.byteLength,
      sha256: new Bun.CryptoHasher("sha256").update(bytes).digest("hex"),
      storage_key: storageKey,
      uploaded_by: ctx.users.get(doc.personKey) ?? preparerId,
      created_at: state.when,
      reviewed_at: state.status === "uploaded" ? null : state.when,
    });
    summary.documents++;
    return docId;
  };

  // Letters are per household, year and kind, so a married couple filing separately shares one.
  const letters = new Map<string, { id: string; sha: string; signers: Set<string>; signed: Set<string>; sentAt: string | null }>();

  function buildReturn(ctx: Ctx, rp: ReturnPlan, year: number, stage: Stage, opts2: { kind?: "original" | "amended"; amends?: string; returning: boolean; extra?: string }) {
    const kind = opts2.kind ?? "original";
    const yearOffset = year - taxYear;
    const history = yearOffset < 0 && kind === "original";
    const createdDays = (history ? 380 : 4) + STAGES.indexOf(stage) * 6 + rng.int(0, 4);
    const created = at(createdDays);
    const stageChanged = at(history ? createdDays - 50 : rng.int(0, Math.min(12, createdDays - 1)));
    const engId = rng.id();
    const hh = ctx.hhId;
    const pid = (k: string) => ctx.people.get(k)!.id;
    const filers = [rp.primary, ...(rp.spouse ? [rp.spouse] : [])];

    insert("engagements", {
      id: engId,
      household_id: hh,
      tax_year: year,
      kind,
      amends_id: opts2.amends ?? null,
      filing_status: reached(stage, "documents") ? rp.status : null,
      stage,
      stage_changed_at: stageChanged,
      created_at: created,
    });
    summary.returns++;
    const onReturn = (key: string, role: string, dep?: { relationship: string; months: number }) =>
      insert("return_people", {
        engagement_id: engId,
        person_id: pid(key),
        tax_year: year,
        engagement_kind: kind,
        role,
        relationship: dep?.relationship ?? null,
        months_lived_with: dep?.months ?? null,
      });
    onReturn(rp.primary, "primary");
    if (rp.spouse) onReturn(rp.spouse, "spouse");
    rp.dependents.forEach((d) => onReturn(d.key, "dependent", d));
    event("engagement.created", { kind: "preparer", userId: preparerId }, { household: hh, engagement: engId, subjectType: "engagement", subjectId: engId, when: created });
    if (stage !== "invited") {
      event("engagement.stage_changed", { kind: "preparer", userId: preparerId }, { household: hh, engagement: engId, subjectType: "engagement", subjectId: engId, when: stageChanged });
    }
    const primaryUser = ctx.users.get(rp.primary)!;
    const between = (a: number, b: number) => at(createdDays - (createdDays - Math.max(0, stageChangeDaysAgo())) * (a + (b - a) * rng.next()));
    function stageChangeDaysAgo() {
      return (anchorMs - Date.parse(stageChanged)) / DAY;
    }

    // Intake
    if (reached(stage, "intake")) {
      const submitted = reached(stage, "documents") ? between(0.2, 0.3) : null;
      insert("intake_responses", { engagement_id: engId, form_version: 1, answers: INTAKE_ANSWERS, updated_at: submitted ?? between(0.3, 0.9), submitted_at: submitted });
      if (submitted) event("intake.submitted", { kind: "client", userId: primaryUser }, { household: hh, engagement: engId, subjectType: "intake", subjectId: engId, when: submitted });
    }
    if (opts2.extra === "question" && reached(stage, "intake")) {
      const asked = between(0.2, 0.4);
      const answered = between(0.5, 0.8);
      insert("requests", {
        id: rng.id(), engagement_id: engId, kind: "question", title: `Did you move during ${year}?`, status: "fulfilled",
        response: "No, same address all year.", responded_at: answered, closed_at: answered, created_by: preparerId, created_at: asked,
      });
    }

    // Sources, requests and documents
    if (reached(stage, "documents")) {
      const activeSources = rp.sources.filter((k) => {
        const s = ctx.plan.sources.find((x) => x.key === k)!;
        return (s.firstYearOffset ?? -99) <= yearOffset && yearOffset <= (s.lastYearOffset ?? 99);
      });
      activeSources.forEach((k) => insert("return_sources", { engagement_id: engId, source_id: ctx.sources.get(k)! }));

      const wanted: { kind: string; personKey: string; sourceKey?: string }[] = [];
      activeSources.forEach((k) => {
        const s = ctx.plan.sources.find((x) => x.key === k)!;
        SOURCE_DOCUMENT_KINDS[s.kind].forEach((kind) => wanted.push({ kind, personKey: s.owners[0]!, sourceKey: k }));
      });
      rp.extraDocs.forEach((kind) => wanted.push({ kind, personKey: rp.primary }));

      const allDone = reached(stage, "ready");
      wanted.forEach((w, i) => {
        const reqId = rng.id();
        const asked = between(0.3, 0.4);
        const src = w.sourceKey ? ctx.plan.sources.find((x) => x.key === w.sourceKey) : undefined;
        const label = src ? `${w.kind.toUpperCase().replace(/_/g, "-")} · ${src.label}` : w.kind.replace(/_/g, " ");
        // At the documents stage some items are in, some are waiting on review, some are still missing.
        const progress = allDone ? "accepted" : opts2.extra === "rejected_doc" && i === 0 ? "rejected" : rng.pick(["accepted", "uploaded", "missing"] as const);
        const fulfilled = progress === "accepted";
        const closedAt = fulfilled ? between(0.6, 0.9) : null;
        insert("requests", {
          id: reqId, engagement_id: engId, person_id: pid(w.personKey), source_id: w.sourceKey ? ctx.sources.get(w.sourceKey)! : null,
          kind: "document", document_kind: w.kind, title: `Upload your ${label}`, status: fulfilled ? "fulfilled" : "open",
          created_by: preparerId, created_at: asked, closed_at: closedAt,
        });
        if (progress === "missing") return;
        const uploadedAt = between(0.45, 0.6);
        const docId = writeDoc(
          ctx,
          { kind: w.kind, personKey: w.personKey, engagementId: engId, year, requestId: reqId, sourceKey: w.sourceKey, sourceLabel: src?.label },
          progress === "rejected"
            ? { status: "rejected", when: uploadedAt, rejectReason: "The photo is too blurry to read. Please upload a clearer copy." }
            : { status: progress, when: uploadedAt },
        );
        const uploader = ctx.users.get(w.personKey);
        event("document.uploaded", uploader ? { kind: "client", userId: uploader } : { kind: "preparer", userId: preparerId }, { household: hh, engagement: engId, subjectType: "document", subjectId: docId, when: uploadedAt });
        if (progress !== "uploaded") {
          event(`document.${progress}`, { kind: "preparer", userId: preparerId }, { household: hh, engagement: engId, subjectType: "document", subjectId: docId, when: closedAt ?? uploadedAt });
        }
      });

      // New clients also send a photo ID once; it belongs to the person, not the year.
      if (!opts2.returning && kind === "original" && !history) {
        writeDoc(ctx, { kind: "photo_id", personKey: rp.primary }, { status: allDone ? "accepted" : "uploaded", when: between(0.4, 0.5) });
      }

      // Engagement letter: drafted at documents, sent by ready, signed by every filer before preparing.
      // A married couple filing separately shares one letter; every other return gets its own.
      const letterKey = `${hh}:${year}:${kind}:${rp.status === "mfs" ? "mfs" : rp.primary}`;
      let letter = letters.get(letterKey);
      if (!letter) {
        const letterReturns = ctx.plan.returns.filter((r) => (rp.status === "mfs" ? r.status === "mfs" : r === rp));
        const nameOf = (k: string) => `${ctx.people.get(k)!.first} ${ctx.people.get(k)!.last}`;
        const filersOfPlan = (r: ReturnPlan) => [r.primary, ...(r.spouse ? [r.spouse] : [])].map(nameOf);
        const { body } = renderLetter(currentTemplate(db), {
          householdName: ctx.plan.displayName,
          taxYear: year,
          amended: kind === "amended",
          date: between(0.3, 0.35).slice(0, 10),
          returns: letterReturns.map((r) => `${FILING_STATUS_LABEL[r.status]} — ${filersOfPlan(r).join(" & ")}`),
          filers: letterReturns.flatMap(filersOfPlan),
        });
        letter = { id: rng.id(), sha: new Bun.CryptoHasher("sha256").update(body).digest("hex"), signers: new Set(), signed: new Set(), sentAt: null };
        const sent = allDone ? between(0.7, 0.8) : null;
        letter.sentAt = sent;
        insert("engagement_letters", {
          id: letter.id, household_id: hh, tax_year: year, template_version: 1, body, body_sha256: letter.sha,
          status: sent ? "sent" : "draft", created_at: between(0.3, 0.35), sent_at: sent,
        });
        if (sent) event("letter.sent", { kind: "preparer", userId: preparerId }, { household: hh, subjectType: "engagement_letter", subjectId: letter.id, when: sent });
        letters.set(letterKey, letter);
      }
      db.run("UPDATE engagements SET letter_id = ? WHERE id = ?", [letter.id, engId]);
      filers.forEach((k) => letter!.signers.add(k));
      const signersNow = reached(stage, "preparing") ? filers : stage === "ready" ? [rp.primary] : [];
      if (signersNow.length && !letter.sentAt) throw new Error("seed bug: signing an unsent letter");
      for (const k of signersNow) {
        const who = ctx.people.get(k)!;
        const signedAt = between(0.8, 0.95);
        insert("signatures", {
          id: rng.id(), letter_id: letter.id, person_id: who.id, user_id: ctx.users.get(k)!, body_sha256: letter.sha,
          typed_name: `${who.first} ${who.last}`, consent_text: CONSENT_TEXT, ip: "192.0.2.10", user_agent: "Demo browser", signed_at: signedAt,
        });
        letter.signed.add(k);
        event("letter.signed", { kind: "client", userId: ctx.users.get(k)! }, { household: hh, engagement: engId, subjectType: "engagement_letter", subjectId: letter.id, when: signedAt });
      }
    }

    // Invoice and payments
    if (reached(stage, "review")) {
      const invId = rng.id();
      const number = `${year + 1}-${String(summary.returns).padStart(4, "0")}${kind === "amended" ? "1" : ""}`;
      const kinds = rp.sources.map((k) => ctx.plan.sources.find((x) => x.key === k)!.kind);
      const lines = suggestedLines(loadFees(db), {
        isAmended: kind === "amended",
        businesses: kinds.filter((k) => k === "business").length,
        rentals: kinds.filter((k) => k === "rental_property").length,
        investments: kinds.includes("brokerage") ? 1 : 0,
      }).map((l) => [l.description, l.quantity, l.unitAmountCents] as [string, number, number]);
      const createdInv = between(0.9, 0.95);
      insert("invoices", { id: invId, engagement_id: engId, number, status: "draft", due_on: `${year + 1}-04-15`, created_at: createdInv });
      lines.forEach(([description, quantity, unit], i) =>
        insert("invoice_lines", { id: rng.id(), invoice_id: invId, position: i + 1, description, quantity, unit_amount_cents: unit }),
      );
      db.run("UPDATE invoices SET status = 'issued', issued_at = ? WHERE id = ?", [createdInv, invId]);
      event("invoice.issued", { kind: "preparer", userId: preparerId }, { household: hh, engagement: engId, subjectType: "invoice", subjectId: invId, when: createdInv });

      const total = lines.reduce((sum, [, q, u]) => sum + q * u, 0);
      const pay = (amount: number, status: "succeeded" | "failed", when: string) => {
        const payId = rng.id();
        insert("payments", {
          id: payId, invoice_id: invId, provider: "stripe", checkout_session_id: `cs_test_demo_${payId.slice(-12)}`, payment_intent_id: `pi_test_demo_${payId.slice(-12)}`,
          amount_cents: amount, status, failure_message: status === "failed" ? "Your card was declined." : null, created_at: when, updated_at: when,
        });
        event(`payment.${status}`, { kind: "stripe" }, { household: hh, engagement: engId, subjectType: "payment", subjectId: payId, when });
      };
      // Half paid by Zelle and recorded by hand: the manual path, alongside Stripe.
      const recordManual = (amount: number, when: string) => {
        const payId = rng.id();
        insert("payments", {
          id: payId, invoice_id: invId, provider: "manual", method: "zelle", received_on: when.slice(0, 10), note: "Deposit via Zelle",
          recorded_by: preparerId, amount_cents: amount, status: "succeeded", created_at: when, updated_at: when,
        });
        event("payment.recorded", { kind: "preparer", userId: preparerId }, { household: hh, engagement: engId, subjectType: "payment", subjectId: payId, when });
      };
      if (reached(stage, "filed")) {
        if (stage === "filed" && opts2.extra === "failed_payment") pay(total, "failed", between(0.95, 0.99));
        else if (stage === "filed" && opts2.extra === "partial_payment") recordManual(Math.round(total / 2), between(0.95, 0.99));
        else pay(total, "succeeded", between(0.95, 0.99));
      }
    }
    return engId;
  }

  db.transaction(() => {
    HOUSEHOLDS.forEach((spec) => {
      const plan = planHousehold(spec, rng, pools);
      const hhId = rng.id();
      insert("households", { id: hhId, display_name: plan.displayName, created_at: at(spec.returning ? 420 : 30) });
      summary.households++;
      const ctx: Ctx = { hhId, plan, spec, people: new Map(), users: new Map(), sources: new Map() };

      for (const p of plan.people) {
        const personId = rng.id();
        const last4 = String(rng.int(0, 9999)).padStart(4, "0");
        insert("people", { id: personId, household_id: hhId, first_name: p.first, last_name: p.last, date_of_birth: p.dob, ssn_last4: last4, created_at: at(30) });
        ctx.people.set(p.key, { id: personId, first: p.first, last: p.last, last4 });
      }

      // Every adult who files gets a login; it's activated once any of their returns is past "invited".
      const filerKeys = new Set(plan.returns.flatMap((r) => [r.primary, ...(r.spouse ? [r.spouse] : [])]));
      const active = plan.returns.some((_, i) => spec.stages[i] !== "invited") || spec.returning;
      for (const key of filerKeys) {
        const p = ctx.people.get(key)!;
        const userId = rng.id();
        const email = emailFor(p.first, p.last);
        insert("users", { id: userId, role: "client", email, person_id: p.id, created_at: at(spec.returning ? 400 : 25), activated_at: active ? at(spec.returning ? 399 : 20) : null });
        ctx.users.set(key, userId);
        if (key === plan.returns[0]!.primary) {
          summary.logins.push({ role: "client", email, label: `${plan.displayName} · ${spec.archetype} · ${spec.stages.join(" + ")}` });
        }
      }
      // Grants: the household's primary filer can see the whole household (dependents' paperwork included).
      const grant = (userId: string) => {
        const grantId = rng.id();
        const when = at(spec.returning ? 399 : 20);
        insert("household_access", { id: grantId, user_id: userId, household_id: hhId, granted_by: preparerId, granted_at: when });
        event("access.granted", { kind: "preparer", userId: preparerId }, { household: hhId, subjectType: "household_access", subjectId: grantId, when });
      };
      grant(ctx.users.get(plan.returns[0]!.primary)!);
      if (spec.delegate) {
        const helperId = rng.id();
        const first = rng.take(pools.first);
        const last = plan.people[0]!.last;
        insert("people", { id: helperId, household_id: null, first_name: first, last_name: last, ssn_last4: String(rng.int(0, 9999)).padStart(4, "0"), created_at: at(20) });
        const helperUser = rng.id();
        const email = emailFor(first, last);
        insert("users", { id: helperUser, role: "client", email, person_id: helperId, created_at: at(20), activated_at: at(19) });
        grant(helperUser);
        summary.logins.push({ role: "client", email, label: `${plan.displayName} · adult child managing a parent's account` });
      }

      for (const s of plan.sources) {
        const sourceId = rng.id();
        insert("sources", {
          id: sourceId, household_id: hhId, kind: s.kind, label: s.label,
          first_year: s.firstYearOffset !== undefined ? taxYear + s.firstYearOffset : null,
          last_year: s.lastYearOffset !== undefined ? taxYear + s.lastYearOffset : null,
          created_at: at(spec.returning ? 400 : 20),
        });
        s.owners.forEach((o) => insert("source_owners", { source_id: sourceId, person_id: ctx.people.get(o)!.id }));
        ctx.sources.set(s.key, sourceId);
      }

      const returning = !!(spec.returning || spec.amended);
      if (returning) {
        // Last season, finished: this is what the returning-client checklist reads.
        const prior = plan.returns.map((rp) => buildReturn(ctx, rp, taxYear - 1, "complete", { returning: false }));
        if (spec.amended) {
          buildReturn(ctx, plan.returns[0]!, taxYear - 1, "preparing", { kind: "amended", amends: prior[0]!, returning: true });
        }
      }
      plan.returns.forEach((rp, i) => buildReturn(ctx, rp, taxYear, spec.stages[i]!, { returning, extra: spec.extra }));
    });

    // A letter is signed once every filer on every return it covers has signed.
    for (const l of letters.values()) {
      if (l.sentAt && [...l.signers].every((k) => l.signed.has(k))) {
        db.run("UPDATE engagement_letters SET status = 'signed' WHERE id = ?", [l.id]);
      }
    }
  })();

  return summary;
}

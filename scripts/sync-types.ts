// Emits the server's AppRouter contract and copies it into each frontend as src/lib/app-router.d.ts.
// Run after changing any procedure, then commit the copies. The frontends never import server source,
// so they typecheck and build without Bun types (skelly-admin's rule). contract.test.ts fails if a
// committed copy is stale.
import { $ } from "bun";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
await $`bun scripts/emit-types.ts`.cwd(resolve(root, "apps/server")).quiet();
const contract = readFileSync(resolve(root, "apps/server/dist/types/appRouter.d.ts"), "utf8");
export const HEADER =
  "// Generated by `bun run sync:types` from apps/server/src/appRouter.ts. Do not edit.\n" +
  "// When a procedure changes, run the sync again and commit the result.\n\n";
for (const app of ["portal", "admin"]) {
  writeFileSync(resolve(root, `apps/${app}/src/lib/app-router.d.ts`), HEADER + contract);
  console.log(`✔ apps/${app}/src/lib/app-router.d.ts`);
}
